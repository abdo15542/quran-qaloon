export interface MushafPageRange { page: number; startSurah: number; startAyah: number; endSurah: number; endAyah: number; }

export function getMushafPageRange(page: number): MushafPageRange | null {
  if (page < 1 || page > 604) return null;
  const [s0, a0, s1, a1] = MUSHAF_PAGES[page - 1];
  return { page, startSurah: s0, startAyah: a0, endSurah: s1, endAyah: a1 };
}

// Last-read page, so the Home card can offer to resume where the reader stopped.
const LAST_PAGE_KEY = "mushaf_last_page";

export function getLastMushafPage(): number {
  try {
    const raw = localStorage.getItem(LAST_PAGE_KEY);
    const p = raw ? parseInt(raw, 10) : NaN;
    if (!isNaN(p) && p >= 1 && p <= 604) return p;
  } catch {
    // storage unavailable
  }
  return 1;
}

export function setLastMushafPage(page: number): void {
  try {
    localStorage.setItem(LAST_PAGE_KEY, String(page));
  } catch {
    // storage unavailable
  }
}

// Page of a given ayah (binary search over the 604 ranges).
export function getPageOfAyah(surahNumber: number, ayahNumber: number): number {
  let lo = 0, hi = 603;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    const [s0, a0, s1, a1] = MUSHAF_PAGES[mid];
    const before = surahNumber < s0 || (surahNumber === s0 && ayahNumber < a0);
    const after = surahNumber > s1 || (surahNumber === s1 && ayahNumber > a1);
    if (before) hi = mid - 1;
    else if (after) lo = mid + 1;
    else return mid + 1;
  }
  return 1;
}
