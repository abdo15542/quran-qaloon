/** Surahs with a section outline (verified at build time). */
export const SURAHS_WITH_SECTIONS_COUNT = 111;

/** Surahs with NO section outline in the source — the UI falls back to
 *  showing those surahs' QUL topics instead of inventing an outline. */
export const SURAHS_WITHOUT_SECTIONS: number[] = [1, 42, 44];

/** A surah's sections, or [] when the source has no outline for it. */
export function getSurahSections(surah: number): SurahSection[] {
  return SURAH_SECTIONS[surah] ?? [];
}
